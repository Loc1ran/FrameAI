"""Copy the downloaded .cube pack into the Android assets and write LutPack.

Warm Film and Cool Cinema stay the demo ids. Every other parsed 3D cube is added
beside them. identity_4 is left untouched.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "app" / "src" / "main" / "assets" / "luts"
PACK_KT = ROOT / "app" / "src" / "main" / "java" / "com" / "team" / "frameai" / "lut" / "LutPack.kt"
DEFAULT_SOURCE = Path(r"C:\Users\loctn\Downloads\lut-20261114T205115Z-1-001\lut")
RESERVED = {"identity_4"}
PINS = (("warm_film", "Warm Film"), ("cool_cinema", "Cool Cinema"))


def slug(stem: str) -> str:
    text = re.sub(r"[^a-z0-9]+", "_", stem.strip().lower())
    text = re.sub(r"_+", "_", text).strip("_")
    return text or "lut"


def display_name(stem: str) -> str:
    return re.sub(r"\s+", " ", stem).strip()


def escape_kotlin(value: str) -> str:
    return value.replace("\\", "\\\\").replace("\"", "\\\"")


def write_pack(entries: list[tuple[str, str]]) -> None:
    lines = [
        "package com.team.frameai.lut",
        "",
        "/**",
        " * Selectable looks in app/src/main/assets/luts. Generated by lut_assets/import_downloaded_luts.py.",
        " * Warm Film and Cool Cinema are the demo chips. Other ids include camera-log conversions,",
        " * which are a poor match for a normal phone JPEG.",
        " */",
        "object LutPack {",
        "    data class Look(val id: String, val name: String)",
        "",
        "    val looks: List<Look> = listOf(",
    ]
    for lut_id, name in entries:
        lines.append(f'        Look("{escape_kotlin(lut_id)}", "{escape_kotlin(name)}"),')
    lines.extend(
        [
            "    )",
            "",
            "    val ids: Set<String> = looks.map { it.id }.toSet()",
            "}",
            "",
        ]
    )
    PACK_KT.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> None:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    if not source.is_dir():
        raise SystemExit(f"LUT folder not found: {source}")
    ASSET_DIR.mkdir(parents=True, exist_ok=True)
    used: set[str] = set(RESERVED)
    copied: list[tuple[str, str]] = []
    for path in sorted(source.glob("*.cube"), key=lambda item: item.name.lower()):
        base = slug(path.stem)
        candidate = base
        suffix = 2
        while candidate in used:
            candidate = f"{base}_{suffix}"
            suffix += 1
        used.add(candidate)
        target = ASSET_DIR / f"{candidate}.cube"
        if not target.exists() or target.read_bytes() != path.read_bytes():
            shutil.copyfile(path, target)
        copied.append((candidate, display_name(path.stem)))
    copied.sort(key=lambda item: item[1].lower())
    entries = list(PINS) + [item for item in copied if item[0] not in {pin[0] for pin in PINS}]
    ids = [item[0] for item in entries]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate LUT ids")
    for pin, _name in PINS:
        if not (ASSET_DIR / f"{pin}.cube").is_file():
            raise SystemExit(f"missing demo LUT {pin}.cube")
    write_pack(entries)
    print(f"bundled {len(entries)} selectable LUTs from {len(copied)} files")


if __name__ == "__main__":
    main()
