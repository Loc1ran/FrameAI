"""Write the selectable LUT catalog from the cubes already in the app assets."""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "app" / "src" / "main" / "assets" / "luts"
PACK_KT = ROOT / "app" / "src" / "main" / "java" / "com" / "team" / "frameai" / "lut" / "LutPack.kt"
CATALOG = ROOT / "contracts" / "luts.json"
SCHEMAS = (
    ROOT / "contracts" / "shot-review.schema.json",
    ROOT / "contracts" / "live-coach.schema.json",
)
PINS = {"warm_film": "Warm Film", "cool_cinema": "Cool Cinema"}
SKIP = {"identity_4"}
TECHNICAL = ("_log", "logc", "log2", "rec709", "cinelike", "bmcc", "ursa", "alexa", "cinestyle", "inspire")


def display_name(stem: str) -> str:
    if stem in PINS:
        return PINS[stem]
    parts = []
    for part in stem.split("_"):
        parts.append(part.upper() if part in {"dji", "exr", "bm"} else part.capitalize())
    return " ".join(parts)


def technical(stem: str) -> bool:
    text = stem.lower()
    return any(marker in text for marker in TECHNICAL)


def kotlin_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace("\"", "\\\"")


def main() -> None:
    looks = []
    for path in sorted(ASSET_DIR.glob("*.cube"), key=lambda item: item.stem.lower()):
        stem = path.stem
        if stem in SKIP:
            continue
        looks.append(
            {
                "id": stem,
                "name": display_name(stem),
                "sourceAsset": path.name,
                "phoneJpeg": not technical(stem),
            }
        )
    pins = [item for item in looks if item["id"] in PINS]
    phone = sorted((item for item in looks if item["phoneJpeg"] and item["id"] not in PINS), key=lambda item: item["name"].lower())
    camera = sorted((item for item in looks if not item["phoneJpeg"]), key=lambda item: item["name"].lower())
    ordered = pins + phone + camera
    ids = [item["id"] for item in ordered]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate LUT ids")

    lines = [
        "package com.team.frameai.lut",
        "",
        "/**",
        " * Every bundled .cube except identity_4.",
        " * phoneJpeg looks are grades for a normal phone photo.",
        " * The others are camera-log conversions and stay selectable, but they are a poor match for a phone JPEG.",
        " * Generated by lut_assets/write_lut_catalog.py.",
        " */",
        "object LutPack {",
        "    data class Look(",
        "        val id: String,",
        "        val name: String,",
        "        val sourceAsset: String,",
        "        val phoneJpeg: Boolean,",
        "    )",
        "",
        "    val looks: List<Look> = listOf(",
    ]
    for item in ordered:
        flag = "true" if item["phoneJpeg"] else "false"
        lines.append(
            "        Look(\"%s\", \"%s\", \"%s\", %s),"
            % (kotlin_string(item["id"]), kotlin_string(item["name"]), kotlin_string(item["sourceAsset"]), flag)
        )
    lines.extend(
        [
            "    )",
            "",
            "    val ids: Set<String> = looks.map { it.id }.toSet()",
            "",
            "    /** Strength the review screen passes to the grader. */",
            "    const val REVIEW_INTENSITY = 0.85f",
            "}",
            "",
        ]
    )
    PACK_KT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    CATALOG.write_text(json.dumps({"looks": ordered}, indent=2) + "\n", encoding="utf-8", newline="\n")
    allowed = ids + ["none"]
    for schema_path in SCHEMAS:
        schema = json.loads(schema_path.read_text(encoding="utf-8"))
        schema["properties"]["suggestedLutId"]["enum"] = allowed
        schema_path.write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(ordered)} looks, {sum(item['phoneJpeg'] for item in ordered)} for phone photos")


if __name__ == "__main__":
    main()
